#!/usr/bin/env node
/* Writes the stock stories' picture prompts into the shared cartoon service (familyboardbooks worker),
   as worker/src/readers.js. Run after changing assets/js/readers.js:
     node tools/export_worker.js ../familyboardbooks/worker/src/readers.js
   Only the picture descriptions go to the service; the words of each story stay on this site.
   Every Learn to Read book uses the same style and the same outfits, so the characters drawn for one book
   can be copied into the family's other books and look the same in all of them. */
"use strict";
var fs = require("fs");
var readers = require("../assets/js/readers.js");
var out = process.argv[2];
if (!out) { console.error("Usage: node tools/export_worker.js <path to worker/src/readers.js>"); process.exit(1); }

var STYLE = "a bright, friendly early-reader illustration: clean soft ink outlines, cheerful flat colours with gentle shading, " +
  "simple uncluttered backgrounds, expressive happy faces and slightly simplified shapes, the same look on every page. " +
  "Not 3D, not anime, not photographic, and not like any animated film or existing book series";
var ROLES = {
  child: { name: "the child", costume: "a sunny yellow T-shirt, blue jeans and red trainers",
    standin: "a cheerful five-year-old child with a round face, rosy cheeks and short curly brown hair" },
  adult: { name: "the grown-up", costume: "a green jumper, dark trousers and comfortable brown shoes",
    standin: "a friendly, smiling grown-up in their thirties with short dark hair" },
  pet: { name: "the pet", costume: "nothing at all, just their own fur or feathers and a plain red collar if they wear one",
    standin: "a small scruffy brown and white dog with floppy ears and a waggy tail" }
};

var READERS = {};
readers.forEach(function (b) {
  var roles = {}, scenes = {};
  b.cast.forEach(function (r) { roles[r] = Object.assign({}, ROLES[r]); });
  b.pages.forEach(function (p, i) {
    var desc = p.d.replace(/\{(\w+)\}/g, function (_, r) { return ROLES[r].name; }).replace(/\.$/, "");
    var cast = b.cast.filter(function (r) { return p.d.indexOf("{" + r + "}") >= 0; });
    var sc = scenes[i + 1] = { cast: cast, text: i % 2 ? "left" : "right", others: /farmer|museum|stall|fair/.test(p.d), desc: desc };
    Object.keys(p.w || {}).forEach(function (r) {  // a different outfit on this page
      var key = "outfit" + (Object.keys(roles[r]).length);
      Object.keys(roles[r]).forEach(function (k) { if (roles[r][k] === p.w[r]) key = k; });
      roles[r][key] = p.w[r]; (sc.wear = sc.wear || {})[r] = key;
    });
  });
  READERS[b.id] = { title: b.title, brand: "FLR", stage: b.stage, style: STYLE, roles: roles, scenes: scenes };
});

fs.writeFileSync(out, "// Family Learn to Read stock stories: picture prompts only.\n" +
  "// GENERATED by tools/export_worker.js in the familylearntoread repo from assets/js/readers.js. Edit there, then run it again.\n" +
  "// Every book shares one style and one set of outfits, so a family's characters can be copied from book to book.\n" +
  "export const READERS = " + JSON.stringify(READERS, null, 1) + ";\n");
console.log("Wrote " + Object.keys(READERS).length + " stories to " + out);
